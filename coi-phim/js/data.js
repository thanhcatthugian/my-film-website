// Khởi tạo LocalStorage nếu chưa có hoặc cập nhật khi có dữ liệu mới (50 phim)
function initDatabase() {
    const storedMovies = localStorage.getItem("coiphim_movies");
    if (!storedMovies || JSON.parse(storedMovies).length < 50) {
        localStorage.setItem("coiphim_movies", JSON.stringify(INITIAL_MOVIES));
    }
    if (!localStorage.getItem("coiphim_categories")) {
        localStorage.setItem("coiphim_categories", JSON.stringify(INITIAL_CATEGORIES));
    }
    // Đồng bộ danh sách người dùng với INITIAL_USERS
    const storedUsersJson = localStorage.getItem("coiphim_users");
    if (!storedUsersJson) {
        localStorage.setItem("coiphim_users", JSON.stringify(INITIAL_USERS));
    } else {
        try {
            let users = JSON.parse(storedUsersJson);
            let updated = false;
            // Đồng bộ thông tin các tài khoản mặc định (admin, user, cinephile) theo INITIAL_USERS
            INITIAL_USERS.forEach(initUser => {
                const existingIdx = users.findIndex(u => u.username.toLowerCase() === initUser.username.toLowerCase());
                if (existingIdx !== -1) {
                    if (users[existingIdx].fullName !== initUser.fullName ||
                        users[existingIdx].role !== initUser.role ||
                        users[existingIdx].avatar !== initUser.avatar) {
                        users[existingIdx].fullName = initUser.fullName;
                        users[existingIdx].role = initUser.role;
                        users[existingIdx].avatar = initUser.avatar;
                        updated = true;
                    }
                } else {
                    users.push(initUser);
                    updated = true;
                }
            });
            if (updated) {
                localStorage.setItem("coiphim_users", JSON.stringify(users));
            }
        } catch (e) {
            localStorage.setItem("coiphim_users", JSON.stringify(INITIAL_USERS));
        }
    }
}

